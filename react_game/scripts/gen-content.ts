// Generates the shared game content from react/src/data/seed.ts (the single source of truth):
//   supabase/seed.sql                → Supabase / PostgreSQL
//   flutter/lib/data/seed.g.dart     → Flutter offline mode
// Run: npm run content   (from react/)
import { mkdirSync, writeFileSync } from 'node:fs';
import * as S from '../src/data/seed.ts';

const root = (p: string) => new URL(`../../${p}`, import.meta.url);

// ------------------------------------------------------------------ SQL
const sqlLit = (v: unknown): string =>
  v === null || v === undefined ? 'null'
  : typeof v === 'number' || typeof v === 'boolean' ? String(v)
  : `'${String(v).replace(/'/g, "''")}'`;

function insert(table: string, idCol: string, rows: object[]): string {
  const cols = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${cols.map((c) => sqlLit((r as Record<string, unknown>)[c])).join(', ')})`).join(',\n');
  return `insert into public.${table} (${cols.join(', ')}) overriding system value values\n${values};\n` +
    `select setval(pg_get_serial_sequence('public.${table}', '${idCol}'), (select max(${idCol}) from public.${table}));\n`;
}

const sql = [
  '-- Generated by react/scripts/gen-content.ts from react/src/data/seed.ts. Do not edit by hand.',
  insert('word_bank', 'word_id', S.WORD_BANK),
  insert('ghost_type', 'ghost_id', S.GHOST_TYPES),
  insert('haunted_places', 'place_id', S.HAUNTED_PLACES),
  insert('items', 'item_id', S.ITEMS),
  insert('place_ghosts', 'place_ghost_id', S.PLACE_GHOSTS),
  insert('ghost_required_items', 'requirement_id', S.GHOST_REQUIRED_ITEMS),
  insert('place_item_spawns', 'spawn_id', S.PLACE_ITEM_SPAWNS),
].join('\n');
writeFileSync(root('supabase/seed.sql'), sql);

// ----------------------------------------------------------------- Dart
const camel = (s: string) => s.replace(/_([a-z])/g, (_, c: string) => c.toUpperCase());
const ENUM_FIELDS: Record<string, string> = {
  action_type: 'ActionType',
  difficulty: 'Difficulty',
  behavior: 'GhostBehavior',
  hostility: 'Hostility',
  item_type: 'ItemType',
};
const dartStr = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;
const dartVal = (key: string, v: unknown): string => {
  if (ENUM_FIELDS[key]) return `${ENUM_FIELDS[key]}.${camel(String(v))}`;
  if (typeof v === 'string') return dartStr(v);
  return String(v);
};
function dartList(name: string, cls: string, rows: object[]): string {
  const body = rows
    .map((r) => `  ${cls}(${Object.entries(r).map(([k, v]) => `${camel(k)}: ${dartVal(k, v)}`).join(', ')}),`)
    .join('\n');
  return `const ${name} = <${cls}>[\n${body}\n];\n`;
}

const dart = [
  '// GENERATED by react/scripts/gen-content.ts from react/src/data/seed.ts. Do not edit by hand.',
  "import '../models/db.dart';",
  '',
  dartList('seedWordBank', 'WordBankRow', S.WORD_BANK),
  dartList('seedGhostTypes', 'GhostType', S.GHOST_TYPES),
  dartList('seedHauntedPlaces', 'HauntedPlace', S.HAUNTED_PLACES),
  dartList('seedItems', 'Item', S.ITEMS),
  dartList('seedPlaceGhosts', 'PlaceGhostRow', S.PLACE_GHOSTS),
  dartList('seedGhostRequiredItems', 'GhostRequiredItem', S.GHOST_REQUIRED_ITEMS),
  dartList('seedPlaceItemSpawns', 'PlaceItemSpawn', S.PLACE_ITEM_SPAWNS),
].join('\n');
mkdirSync(root('flutter/lib/data'), { recursive: true });
writeFileSync(root('flutter/lib/data/seed.g.dart'), dart);

console.log('wrote supabase/seed.sql and flutter/lib/data/seed.g.dart');
